// `npm run assets`: rebuilds src/assets/models/*.glb from scripts/assets/assets.json.
// Every asset is public domain (CC0): free for commercial use, no attribution required.
// Downloads each source once into .cache/assets/, runs it through Blender (blender_build.py:
// one mesh, triangle budget, small textures, origin where the game holds it), and rewrites
// src/assets/models/LICENSES.md with where every file came from.
// Needs Blender on PATH (or BLENDER=/path/to/blender).
import { mkdirSync, existsSync, writeFileSync, readFileSync, statSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname } from 'node:path';

const root = new URL('../../', import.meta.url).pathname;
const list = JSON.parse(readFileSync(`${root}scripts/assets/assets.json`, 'utf8'));
const only = process.argv.slice(2); // optional: build just these ids
const blender = process.env.BLENDER || 'blender';
const json = async (url) => (await fetch(url)).json();

async function download(url, path) {
  if (existsSync(path) && statSync(path).size > 0) return;
  mkdirSync(dirname(path), { recursive: true });
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  writeFileSync(path, Buffer.from(await res.arrayBuffer()));
}

// Poly Haven: the 1k glTF and its textures (we shrink them further in Blender)
async function polyhaven(a) {
  const dir = `${root}.cache/assets/polyhaven/${a.id}`;
  const files = await json(`https://api.polyhaven.com/files/${a.id}`);
  const g = files.gltf['1k'].gltf;
  const main = `${dir}/${a.id}.gltf`;
  await download(g.url, main);
  for (const [rel, f] of Object.entries(g.include ?? {})) await download(f.url, `${dir}/${rel}`);
  const info = await json(`https://api.polyhaven.com/info/${a.id}`);
  return { file: main, name: info.name, authors: Object.keys(info.authors ?? {}).join(', '), page: `https://polyhaven.com/a/${a.id}` };
}

// Only libraries where every single asset is CC0 belong here (Poly Haven, ambientCG, Kenney, Quaternius):
// then nothing with a non-commercial or attribution licence can get into the game by mistake.
const SOURCES = { polyhaven };
const rows = [];
for (const a of list) {
  const src = await SOURCES[a.source](a);
  const out = `${root}src/assets/models/${a.id}.glb`;
  if (!only.length || only.includes(a.id)) {
    const log = execFileSync(blender, ['-b', '--factory-startup', '--python', `${root}scripts/assets/blender_build.py`, '--', src.file, out, String(a.tris), String(a.tex), a.anchor], { encoding: 'utf8', maxBuffer: 64 << 20 });
    const stats = JSON.parse(log.split('\n').find((l) => l.startsWith('STATS ')).slice(6));
    console.log(`${a.id}: ${stats.tris_before} -> ${stats.tris} tris, ${stats.materials} mat, ${(stats.bytes / 1024).toFixed(0)} KB, ${stats.size_m.join(' x ')} m (${a.for})`);
  }
  rows.push(`| \`${a.id}.glb\` | ${a.for} | [${src.name}](${src.page}) | ${src.authors} | CC0 |`);
}
writeFileSync(
  `${root}src/assets/models/LICENSES.md`,
  [
    '# 3D models',
    '',
    'Generated by `npm run assets` from `scripts/assets/assets.json`. Every model is CC0 (public domain):',
    'free for any use, commercial included, no attribution required. Authors are listed as a courtesy.',
    '',
    '| File | Used as | Source | Author | License |',
    '|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n'),
);
